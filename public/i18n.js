const translations = {};
const templates = [];
for (const line of catalogue.split('\n')) {
  const [french, english] = line.split('|');
  if (!french.includes('{')) { translations[french] = english; continue; }
  const names = [];
  const source = french.split(/(\{\w+\})/).map(part => {
    const placeholder = part.match(/^\{(\w+)\}$/);
    if (!placeholder) return part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    names.push(placeholder[1]);
    return placeholder[1] === 'n' ? '(\\d[\\d\\s\\u202f\\u00a0.,]*)' : '(.+?)';
  }).join('');
  templates.push({ pattern: new RegExp('^' + source + '$'), names, english });
}

const localizedFormats = new Map();
function localizedDate(value) {
  const options = { day: 'numeric', month: 'short', year: 'numeric' };
  const date = new Date(value);
  const french = new Intl.DateTimeFormat('fr-FR', options).format(date);
  localizedFormats.set(french, new Intl.DateTimeFormat('en-GB', options).format(date));
  return french;
}

let language = 'fr';
try {
  const saved = localStorage.getItem('hireloop-language');
  if (saved === 'en' || saved === 'fr') language = saved;
} catch (_) { /* Language switching still works when storage is unavailable. */ }
// ?lang=en in the address forces a language, which is handy for sharing a link.
if (typeof location !== 'undefined') {
  const forced = new URLSearchParams(location.search).get('lang');
  if (forced === 'en' || forced === 'fr') language = forced;
}

function translate(text) {
  if (language === 'fr') return text;
  const trimmed = text.trim();
  let result = translations[trimmed];
  if (!result && trimmed) {
    for (const { pattern, names, english } of templates) {
      const match = trimmed.match(pattern);
      if (!match) continue;
      result = english;
      names.forEach((name, i) => { result = result.replace(`{${name}}`, translations[match[i + 1]] || match[i + 1]); });
      break;
    }
  }
  let output = result ? text.replace(trimmed, result) : text;
  for (const [french, english] of localizedFormats) output = output.replaceAll(french, english);
  return output;
}

// Remember source text per node, so switching back is lossless and does not
// rerender forms, discard drafts, change select values or remove listeners.
const sourceText = new WeakMap();
const sourceAttributes = new WeakMap();
// Text inside these elements is user content and is never translated.
const ignoredText = 'script, style, textarea, [translate="no"], .prose';
function localize(root) {
  if (root.nodeType === Node.TEXT_NODE) {
    if (!root.parentElement || root.parentElement.closest(ignoredText)) return;
    const current = root.nodeValue;
    const previous = sourceText.get(root);
    const source = previous && previous.output === current ? previous.source : current;
    const output = translate(source);
    sourceText.set(root, { source, output });
    if (current !== output) root.nodeValue = output;
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE || root.matches('[translate="no"], script, style')) return;
  for (const attribute of ['placeholder', 'aria-label', 'title', 'content', 'data-label']) {
    if (!root.hasAttribute(attribute) || (attribute === 'content' && !root.matches('meta[name="description"]'))) continue;
    const records = sourceAttributes.get(root) || {};
    const current = root.getAttribute(attribute);
    const previous = records[attribute];
    const source = previous && previous.output === current ? previous.source : current;
    const output = translate(source);
    records[attribute] = { source, output };
    sourceAttributes.set(root, records);
    if (current !== output) root.setAttribute(attribute, output);
  }
  for (const child of root.childNodes) localize(child);
}

function updateLanguage() {
  document.documentElement.lang = language;
  for (const button of document.querySelectorAll('[data-language]')) {
    button.setAttribute('aria-pressed', String(button.dataset.language === language));
  }
  localize(document.documentElement);
}

document.addEventListener('click', event => {
  const button = event.target.closest('[data-language]');
  if (!button) return;
  language = button.dataset.language;
  try { localStorage.setItem('hireloop-language', language); } catch (_) { /* Optional persistence. */ }
  updateLanguage();
});

updateLanguage();
// Every route, validation message and notification goes through the same catalogue.
// Only changed subtrees are observed rather than repeatedly scanning pages.
new MutationObserver(records => {
  for (const record of records) {
    if (record.type === 'childList') record.addedNodes.forEach(localize);
    else localize(record.target);
  }
}).observe(document.documentElement, {
  childList: true, subtree: true, characterData: true, attributes: true,
  attributeFilter: ['placeholder', 'aria-label', 'title', 'content', 'data-label'],
});
